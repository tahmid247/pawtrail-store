"use client";
import { useRouter } from "next/navigation";
import { authClient } from "@/lib/auth-client";

export function SignOutButton() {
  const router = useRouter();
  return (
    <button
      className="block w-full whitespace-nowrap rounded-xl px-3 py-2 text-left text-sm font-medium text-muted hover:bg-lavender-pale hover:text-danger"
      onClick={async () => {
        await authClient.signOut();
        router.push("/");
        router.refresh();
      }}
    >
      Sign out
    </button>
  );
}
